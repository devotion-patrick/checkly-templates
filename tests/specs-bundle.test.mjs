// src/deploy/specs: one self-contained bundle per Playwright kind that has its own spec.

import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { MODULES, repoRoot } from './helpers.mjs';

const specsDir = path.join(repoRoot, 'src', 'deploy', 'specs');

const kindsWithSpec = MODULES.filter((m) => m.isPlaywright === true)
  .map((m) => m.kind)
  .filter((kind) => {
    const dir = path.join(repoRoot, 'src', 'checks', kind, '__checks__');
    return fs.existsSync(dir) && fs.readdirSync(dir).some((f) => f.endsWith('.spec.ts'));
  })
  .sort();

const bundles = fs.existsSync(specsDir) ? fs.readdirSync(specsDir).sort() : [];

// require("x"), import "x", import ... from "x", import("x")
const SPECIFIER = /\brequire\(\s*["']([^"']+)["']\s*\)|\bimport\s*\(\s*["']([^"']+)["']\s*\)|\bimport\s+(?:[^"';]+?\s+from\s+)?["']([^"']+)["']/g;

function specifiersOf(source) {
  return [...source.matchAll(SPECIFIER)].map((m) => m[1] ?? m[2] ?? m[3]);
}

describe('specs bundles', () => {
  it('has a bundle for every Playwright kind with a spec, and nothing else', () => {
    assert.ok(kindsWithSpec.length > 0);
    assert.deepEqual(bundles, kindsWithSpec.map((k) => `${k}.spec.js`));
  });

  it('skips Playwright kinds that reuse another kind\'s spec', () => {
    assert.ok(!bundles.includes('restricted-admin.spec.js'));
  });

  for (const name of bundles) {
    const source = fs.readFileSync(path.join(specsDir, name), 'utf8');
    const specifiers = specifiersOf(source);

    it(`${name}: has no relative require or import`, () => {
      const relative = specifiers.filter((s) => s.startsWith('.') || s.startsWith('/'));
      assert.deepEqual(relative, []);
    });

    it(`${name}: requires only @playwright/test and node: built-ins`, () => {
      const other = specifiers.filter((s) => s !== '@playwright/test' && !s.startsWith('node:'));
      assert.deepEqual(other, []);
      assert.ok(specifiers.includes('@playwright/test'));
    });

    it(`${name}: carries the generated-file banner`, () => {
      assert.match(source, /^\/\/ Generated by src\/deploy\/build-specs\.mjs\./);
    });
  }
});
