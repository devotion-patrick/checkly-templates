#!/usr/bin/env node
// Writes src/deploy/specs/<kind>.spec.js: one self-contained bundle per Playwright kind's spec.
//
//   node src/deploy/build-specs.mjs            # write src/deploy/specs/
//   node src/deploy/build-specs.mjs --check    # exit non-zero if missing, stale or extra (used in CI)
//
// The Client Portal deploys through Checkly's REST API, one script per BROWSER check,
// so it can't send a spec that imports local files (gdpr and ccpa import ./grading.ts
// and ../../_privacy/*). It embeds these bundles instead, as it reads manifest.json.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { createJiti } from 'jiti';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..', '..');
const outDir = path.join(here, 'specs');

const BANNER = '// Generated by src/deploy/build-specs.mjs. Do not edit by hand; run "npm run build:specs".';

const jiti = createJiti(import.meta.url);
const { MODULES } = await jiti.import('./registry.ts');

/** Playwright kinds with their own spec, sorted. restricted-admin reuses launch-readiness's. */
function specSources() {
  return MODULES.filter((m) => m.isPlaywright === true)
    .map((m) => m.kind)
    .sort()
    .flatMap((kind) => {
      const dir = path.join(repoRoot, 'src', 'checks', kind, '__checks__');
      const specs = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.spec.ts')) : [];
      if (specs.length > 1) throw new Error(`${kind} has more than one spec: ${specs.join(', ')}`);
      return specs.length ? [{ kind, source: path.join(dir, specs[0]) }] : [];
    });
}

async function bundle(source) {
  const result = await build({
    entryPoints: [source],
    // Relative to the repo, so path comments are the same on every machine.
    absWorkingDir: repoRoot,
    bundle: true,
    write: false,
    platform: 'node',
    format: 'cjs',
    target: 'node18',
    external: ['@playwright/test'],
    legalComments: 'none',
    charset: 'utf8',
    banner: { js: BANNER },
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

const expected = new Map();
for (const { kind, source } of specSources()) {
  expected.set(`${kind}.spec.js`, await bundle(source));
}

if (process.argv.includes('--check')) {
  const fix = 'run "npm run build:specs" in src/deploy/.';
  const problems = [];
  const actual = fs.existsSync(outDir) ? fs.readdirSync(outDir).sort() : [];

  for (const [name, content] of expected) {
    const file = path.join(outDir, name);
    if (!fs.existsSync(file)) problems.push(`${name} missing`);
    else if (fs.readFileSync(file, 'utf8') !== content) problems.push(`${name} stale`);
  }
  for (const name of actual) {
    if (!expected.has(name)) problems.push(`${name} has no source spec`);
  }

  if (problems.length) {
    console.error(`src/deploy/specs is out of date (${problems.join('; ')}); ${fix}`);
    process.exit(1);
  }
  console.log(`src/deploy/specs is up to date (${expected.size} bundles).`);
  process.exit(0);
}

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });
for (const [name, content] of expected) {
  fs.writeFileSync(path.join(outDir, name), content);
}
console.log(`Wrote ${expected.size} bundles to ${path.relative(process.cwd(), outDir)}: ${[...expected.keys()].join(', ')}.`);
