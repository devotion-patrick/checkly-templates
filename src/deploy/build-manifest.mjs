#!/usr/bin/env node
// Writes src/deploy/manifest.json: the per-kind facts a consumer needs when
// it deploys checks itself rather than through `checkly deploy`.
//
//   node src/deploy/build-manifest.mjs            # write src/deploy/manifest.json
//   node src/deploy/build-manifest.mjs --check    # exit non-zero if stale (used in CI)
//
// schema.json answers "is this config valid". This answers "what would the
// factory produce for it": template version, default frequency, Checkly
// checkType. The Client Portal calls Checkly's REST API directly and so
// cannot run the factories, and was hand-maintaining C# copies of all three.
// They drifted, silently and expensively -- an xpath check deployed from the
// portal ran twice as often as the template says, and four kinds went out as
// the wrong construct entirely. This file exists so there is one place those
// facts are stated.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createJiti } from 'jiti';

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.join(here, 'manifest.json');

const jiti = createJiti(import.meta.url);
const { MODULES } = await jiti.import('./registry.ts');

const manifest = {
  $comment:
    'Generated by src/deploy/build-manifest.mjs. Do not edit by hand; '
    + 'run "npm run build:manifest".',
  kinds: Object.fromEntries(
    MODULES.map((module) => [
      module.kind,
      {
        version: module.version,
        checkType: module.checkType,
        isPlaywright: module.isPlaywright === true,
        defaults: {
          ...(module.defaults.frequency ? { frequency: module.defaults.frequency } : {}),
          ...(module.defaults.locations ? { locations: module.defaults.locations } : {}),
        },
      },
    ]),
  ),
};

const next = JSON.stringify(manifest, null, 2) + '\n';

if (process.argv.includes('--check')) {
  if (!fs.existsSync(target)) {
    console.error('manifest.json missing; run "npm run build:manifest" in src/deploy/.');
    process.exit(1);
  }
  if (fs.readFileSync(target, 'utf8') !== next) {
    console.error('manifest.json is stale; run "npm run build:manifest" in src/deploy/.');
    process.exit(1);
  }
  console.log('manifest.json is up to date.');
  process.exit(0);
}

fs.writeFileSync(target, next);
console.log(`Wrote ${path.relative(process.cwd(), target)}.`);
